# Entrada de dados

numero1 = int(input("Digite um número: "))
numero2 = int(input("Digite outro número: "))

# Exibe o resultado da expressão
# Verifica se os números são iguais
print("numero1 == numero2: ", numero1 == numero2)

# Verifica se os números são diferentes
print("numero1 != numero2: ", numero1 != numero2 )

# Verifica se o número 1 é menor que o número 2
print("numero1 < numero2: ", numero1 < numero2)

# Verifica se o número 1 é maior que o número 2
print("numero1 > numero2: ", numero1 > numero2)

# Verifica se o número 1 é menor ou igual que o número 2
print("numero1 <= numero2: ", numero1 <= numero2)

# Verifica se o número 1 é maior ou igual que o número 2
print("numero1 >= numero2: ", numero1 >= numero2)