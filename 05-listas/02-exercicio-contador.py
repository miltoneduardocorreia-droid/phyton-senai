# Criar uma variável chamada contador começando com 1.
# Utilizar um while para verificar se o contador é menor ou igual a 10.
# Mostrar o número atual no console.
# Aumentar o contador em 1 a cada repetição.

contador = 1

# Enquanto o contador for menor ou igual a 5
while contador <= 10:
    # Mostra o valor atual do contador
    print("Contador agora é : ", contador)
    # Aumenta o contador em 1
    contador = contador + 1
# Mostra uma mensagem quando o while termina
print("Contador chegou a 10. While terminou!")