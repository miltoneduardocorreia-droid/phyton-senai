# Criar uma variável para armazenar a idade da pessoa
# Calqule a idade dessa pessoa após  10 anos
# O programe deverá apresentar a idade atual e a idade futura.
# Resultado do terminal:
# Milton Araujo tem 60 anos atualmente.
# Daqui a 10 anos, terá 70 anos

nome = "Milton Araujo"
idade_atual = 60
acrescimo = 10
print(f"{nome} tem {idade_atual} anos")
print(f"{nome} terá {idade_atual + acrescimo} anos")